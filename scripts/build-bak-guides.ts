// BAK-written workshop guides: original BAK text, with numbers checked against the maker's published values.
// Source: docs/research/bak-guides/*.json (arrays of procedures). Output: shared/bak-guide-library.ts.
// Run: node --experimental-strip-types scripts/build-bak-guides.ts
import {readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const dir='docs/research/bak-guides/';
const sha=(v:unknown)=>createHash('sha256').update(typeof v==='string'?v:JSON.stringify(v)).digest('hex');
const banned=/\b(repair manual|owner'?s manual|service manual|ktm says|page \d|pdf \d|licen[cs]e[ds]?\b|watermark)|@|065920|070143|veit/i;
const out:any[]=[];
for(const file of readdirSync(dir).filter(f=>f.endsWith('.json')).sort()){
 const raw=readFileSync(dir+file,'utf8'),list=JSON.parse(raw);
 // A guide written once for a platform generation may list "targets": every exact bike-year whose values were checked to be
 // identical. It is expanded into one guide per bike-year (id gets the year), so each bike's own guide list stays exact.
 const expanded=(Array.isArray(list)?list:list.procedures).flatMap((p:any)=>Array.isArray(p.targets)&&p.targets.length?p.targets.map((t:any)=>{const {targets,...rest}=p;return {...rest,id:`${p.id}-${t.manufacturer}-${t.model}-${t.model_year}`.toLowerCase().replace(/[^a-z0-9-]+/g,'-'),target:{variant:'standard',region:'US',...t}};}):[p]);
 for(const p of expanded){
  if(!/^bak-/.test(p.id))throw Error(`${file}: ${p.id} must start with bak-`);
  const ids=new Set<string>();
  for(const s of p.steps){
   if(ids.has(s.id))throw Error(`${p.id}: duplicate step ${s.id}`);
   for(const d of s.depends_on??[])if(!ids.has(d))throw Error(`${p.id}/${s.id}: depends on later or unknown step ${d}`);
   ids.add(s.id);
   for(const b of s.branches??[])if(!p.steps.some((x:any)=>x.id===b.next_step))throw Error(`${p.id}/${s.id}: branch to unknown step`);
  }
  const text=JSON.stringify(p);
  if(banned.test(text))throw Error(`${p.id}: rider-facing text mentions a manual, page, licence or personal data: ${text.match(banned)![0]}`);
  const body={...p,steps:p.steps.map((s:any)=>({...s,source_pdf_pages:[],source_links:[],diagram_reference_required:false,depends_on:s.depends_on??[],verification:s.verification??[],record_required:!!s.record_required}))};
  delete body.source;delete body.content_sha256;delete body.supplemental_sources;
  const content_sha256=sha(body);
  out.push({...body,content_sha256,source:{source_url:'',document_sha256:content_sha256,document_revision:'BAK MX workshop guide',pdf_pages:[],printed_pages:[],review_status:'BAK_AUTHORED'}});
 }
}
writeFileSync('shared/bak-guide-library.ts','// Generated by scripts/build-bak-guides.ts. Original BAK MX guides; do not edit by hand.\nimport type {ReviewedProcedure} from \'./procedures.ts\';\nexport const bakGuideLibrary:ReviewedProcedure[]='+JSON.stringify(out,null,1)+';\n');
console.log(`${out.length} BAK guides, ${out.reduce((n,p)=>n+p.steps.length,0)} steps`);
