// BAK-written workshop guides: original BAK text, with numbers checked against the maker's published values.
// Source: docs/research/bak-guides/*.json (arrays of procedures). Output: shared/bak-guide-library.ts.
// Run: node --experimental-strip-types scripts/build-bak-guides.ts
import {readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {isRosterBike} from '../shared/garage-models.ts';
const dir='docs/research/bak-guides/';
const sha=(v:unknown)=>createHash('sha256').update(typeof v==='string'?v:JSON.stringify(v)).digest('hex');
const banned=/\b(repair manual|owner'?s manual|service manual|ktm says|page \d|pdf \d|licen[cs]e[ds]?\b|watermark)|@|065920|070143|veit/i;
const out:any[]=[];const groups:any[]=[];
for(const file of readdirSync(dir).filter(f=>f.endsWith('.json')).sort()){
 const raw=readFileSync(dir+file,'utf8'),list=JSON.parse(raw);
 // A guide written once for a platform generation may list "targets": every exact bike-year whose values were checked to be
 // identical. It is expanded into one guide per bike-year (id gets the year), so each bike's own guide list stays exact.
 for(const entry of (Array.isArray(list)?list:list.procedures)){const group:any={x:[]};groups.push(group);
 const expanded=[entry].flatMap((p:any)=>Array.isArray(p.targets)&&p.targets.length?p.targets.map((t:any)=>{const {targets,...rest}=p;return {...rest,id:`${p.id}-${t.manufacturer}-${t.model}-${t.model_year}`.toLowerCase().replace(/[^a-z0-9-]+/g,'-'),target:{variant:'standard',region:'US',...t}};}):[p]);
 for(const p of expanded){
  // a guide for a bike-year the Garage doesn't offer can't be reached by any rider: report it, don't ship it
  if(!isRosterBike(p.target.manufacturer,p.target.model,p.target.model_year)){console.log(`skipped (not a Garage bike-year): ${p.id}`);continue;}
  if(!/^bak-/.test(p.id))throw Error(`${file}: ${p.id} must start with bak-`);
  const ids=new Set<string>();
  for(const s of p.steps){
   if(ids.has(s.id))throw Error(`${p.id}: duplicate step ${s.id}`);
   for(const d of s.depends_on??[])if(!ids.has(d))throw Error(`${p.id}/${s.id}: depends on later or unknown step ${d}`);
   ids.add(s.id);
   for(const b of s.branches??[])if(!p.steps.some((x:any)=>x.id===b.next_step))throw Error(`${p.id}/${s.id}: branch to unknown step`);
  }
  const text=JSON.stringify(p);
  if(banned.test(text))throw Error(`${p.id}: rider-facing text mentions a manual, page, licence or personal data: ${text.match(banned)![0]}`);
  const body={...p,steps:p.steps.map((s:any)=>({...s,source_pdf_pages:[],source_links:[],diagram_reference_required:false,depends_on:s.depends_on??[],verification:s.verification??[],record_required:!!s.record_required}))};
  delete body.source;delete body.content_sha256;delete body.supplemental_sources;
  const content_sha256=sha(body);
  out.push(p.id);
  // Stored once per written guide; each bike-year keeps its own id, target and content hash. Per-step fields that are always
  // the same for BAK guides are added back when the library loads (shared/bak-guides.ts).
  if(!group.p){const {id,target,...rest}=body;group.p={...rest,steps:p.steps.map((st:any)=>({id:st.id,title:st.title,instruction:st.instruction,...(st.depends_on?.length?{depends_on:st.depends_on}:{}),...(st.verification?.length?{verification:st.verification}:{}),...(st.record_required?{record_required:true}:{}),...(st.branches?{branches:st.branches}:{})}))};}
  group.x.push([p.id,p.target.manufacturer,p.target.model,p.target.model_year,p.target.variant??'standard',p.target.region??'US',content_sha256]);
 }
 }
}
// The data is written as one JSON string, not a JavaScript literal: type checkers then see a single string instead of
// inferring a type for megabytes of nested arrays (that inference made hosted builds run past their time limit).
writeFileSync('shared/bak-guide-library.ts','// Generated by scripts/build-bak-guides.ts. Original BAK MX guides; do not edit by hand.\nimport {expandBakGuides,type BakGuideGroup} from \'./bak-guides.ts\';\nconst groups:BakGuideGroup[]=JSON.parse('+JSON.stringify(JSON.stringify(groups.filter(g=>g.p)))+');\nexport const bakGuideLibrary=expandBakGuides(groups);\n');
console.log(`${out.length} BAK guides from ${groups.length} written guides`);
