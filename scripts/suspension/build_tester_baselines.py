"""Tester baseline suspension settings -> server/tester-baselines.ts (private reasoning context for Ask BAK).

usage: python3 scripts/suspension/build_tester_baselines.py
Reads docs/research/suspension-knowledge/specialist/baselines.json (published tester settings, each with its source in the
research file). The generated module keeps the settings, rider and conditions but no source names: the model uses them to
judge where testers typically run a bike, and never shows the numbers or names to riders."""
import json,os,re
root=os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
d=json.load(open(os.path.join(root,'docs','research','suspension-knowledge','specialist','baselines.json')))
def clean(o):
    if isinstance(o,str): return re.sub(r"\b(Kris Keefer|Keefer|Motocross Action|MXA|Gardner Tarlow|Michael Allen|Kenny Day|Steve Havlicek|Drey Dircks|PulpMX|Swapmoto Live|Swapmoto|Vital MX|Dirt Bike magazine|Dirt Bike|Racer X|Cycle News|Transmoto|Dirt Rider|Ultimate Motorcycling)('s)?\b",'a tester',o)
    if isinstance(o,dict): return {k:clean(v) for k,v in o.items() if v not in (None,'',[],{}) and clean(v) not in ('',{},[])}
    return o
out={}
for b in d['baselines']:
    key=f"{b['make']}|{b['model']}|{b['year']}"
    rec=clean({'variant':b.get('variant'),'rider':b.get('rider'),'conditions':b.get('conditions'),'fork':b.get('fork'),'shock':b.get('shock'),'other':b.get('other'),'reasons':b.get('reasons')})
    out.setdefault(key,[]).append(rec)
dst=os.path.join(root,'server','tester-baselines.ts')
open(dst,'w').write('// GENERATED by scripts/suspension/build_tester_baselines.py. Do not edit by hand.\n'
 '// Published tester baseline settings by exact bike, without source names. Private reasoning context: never shown to riders.\n'
 'export type TesterBaseline=Record<string,unknown>;\n'
 'export const testerBaselines:Record<string,TesterBaseline[]>='+json.dumps(out,separators=(',',':'),ensure_ascii=False)+';\n')
print(len(out),'bike-years',sum(map(len,out.values())),'baselines',os.path.getsize(dst)//1024,'KB')
