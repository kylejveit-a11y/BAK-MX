"""Generate shared/garage-models.ts from the reviewed launch roster.

Only exact model-years whose identity is CONFIRMED in docs/research/parts-pass14/launch-targets.json
are offered in the Garage picker, plus the original twelve motocross families for 2022-2026 that
already have published evidence, plus model-years confirmed by an OEM manual on file. Any other bike is entered as an owner-declared identity.
Offering a bike in the picker is identity only; it never implies specification coverage.
"""
import json
from collections import defaultdict
roster=json.load(open('docs/research/parts-pass14/launch-targets.json',encoding='utf-8'))
discipline={(f['manufacturer'],f['model']):f['discipline'] for f in roster['families']}
cycle={(f['manufacturer'],f['model']):f['engine_cycle'] for f in roster['families']}
years=defaultdict(set)
for r in roster['rows']:
    if r['identity_status'].startswith('CONFIRMED') and r.get('region','US')=='US' and r.get('variant','standard')=='standard':
        years[(r['manufacturer'],r['model'])].add(r['model_year'])
original={'Yamaha':['YZ250F','YZ450F'],'Honda':['CRF250R','CRF450R'],'Kawasaki':['KX250','KX450'],'KTM':['250 SX-F','450 SX-F'],'Husqvarna':['FC 250','FC 450'],'GasGas':['MC 250F','MC 450F']}
for make,models in original.items():
    for model in models:
        years[(make,model)].update(range(2022,2027))
        discipline.setdefault((make,model),'motocross');cycle.setdefault((make,model),'4-stroke')
# Exact model-years whose identity is confirmed by the cover of an OEM manual on file (docs/research/manual-index/).
manual_confirmed={('Yamaha','YZ450F'):[2018,2019],('Yamaha','YZ250F'):[2019],
 ('GasGas','MC 250F'):[2027],('GasGas','MC 450F'):[2027],('GasGas','MC 350F'):[2025],('GasGas','EX 450F'):[2025],('Husqvarna','FC 350'):[2025]}
for key,ys in manual_confirmed.items():
    years[key].update(ys)
    discipline.setdefault(key,'motocross');cycle.setdefault(key,'4-stroke')
# Model-years with a complete manufacturer parts catalog on file: the manufacturer's own listing confirms the model-year exists.
for r in json.load(open('docs/research/parts-pass14/INVENTORY_STATUS.json',encoding='utf-8'))['rows']:
    t=r['target']
    if r['catalog_inventory_complete'] and t.get('region','US')=='US' and t.get('variant','standard')=='standard' and (t['manufacturer'],t['model']) in discipline:
        years[(t['manufacturer'],t['model'])].add(t['model_year'])
order={'motocross':0,'cross-country':1,'enduro':2,'enduro-offroad':2}
makes=defaultdict(list)
for (make,model),ys in years.items(): makes[make].append(model)
out={}
for make in sorted(makes):
    out[make]=sorted(makes[make],key=lambda m:(order.get(discipline[(make,m)],3),m))
table={f'{make}|{model}':sorted(ys) for (make,model),ys in sorted(years.items())}
meta={f'{make}|{model}':{'discipline':'enduro' if discipline[(make,model)].startswith('enduro') else discipline[(make,model)],'engine':cycle[(make,model)]} for (make,model) in sorted(years)}
ts='''// GENERATED by scripts/build-garage-roster.py from the reviewed launch roster. Do not edit by hand.
// Selection shortcuts identify bikes; reviewed service applicability is checked separately.
export const garageModels:Record<string,string[]>=%s;
const confirmedYears:Record<string,number[]>=%s;
export const garageModelInfo:Record<string,{discipline:'motocross'|'cross-country'|'enduro';engine:'2-stroke'|'4-stroke'}>=%s;
/** Exact model-years with a confirmed US standard identity. Empty for a bike that is not in the roster. */
export function garageModelYears(make:string,model:string):number[]{return confirmedYears[make+'|'+model]??[];}
export function isRosterBike(make:string,model:string,year:number):boolean{return garageModelYears(make,model).includes(year);}
'''%(json.dumps(out,separators=(',',':')),json.dumps(table,separators=(',',':')),json.dumps(meta,separators=(',',':')))
open('shared/garage-models.ts','w',encoding='utf-8',newline='\n').write(ts)
print(len(years),'families',sum(len(v) for v in years.values()),'model-years')
