"""Build the app's aftermarket data from the research catalogs.

usage: python3 scripts/aftermarket/build_app_data.py
Writes public/parts-catalog/<family>.json (the Garage "What's on your bike" picker, loaded by the browser per family) and
shared/aftermarket-research.ts (researched parts only: what they change, caveats and tester notes, read by the server
when it answers about a bike with those parts fitted). Runs build_catalog.py for each family with APP_OUT set."""
import json,os,re,glob,subprocess,sys
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from textclean import short,brand_name
root=os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FAM=[('ktm-family','KTM family','KTM,Husqvarna,GasGas'),('triumph','Triumph TF','Triumph'),('yamaha','Yamaha YZ','Yamaha'),
     ('honda','Honda CRF','Honda'),('kawasaki','Kawasaki KX','Kawasaki')]
out=os.path.join(root,'public','parts-catalog')
for d,title,makes in FAM:
    r=subprocess.run([sys.executable,os.path.join(root,'scripts','aftermarket','build_catalog.py'),os.path.join(root,'docs','research','aftermarket',d),title,makes],
                     env=dict(os.environ,APP_OUT=out),capture_output=True,text=True)
    if r.returncode: sys.exit(r.stderr)
    print([l for l in r.stdout.splitlines() if l.startswith('app catalog')][0][:90])
research={}
for d,_,_ in FAM:
    c=json.load(open(os.path.join(out,d+'.json')))
    for it in c['items']:
        if not it.get('r'): continue
        research[it['r']]={'brand':c['brands'][it['b']],'product':it['n'],'system':c['systems'][it['s']],'part_numbers':it.get('p',''),
                           'confidence':it.get('conf'),'what_it_changes':it.get('w',''),'caveats':it.get('c',''),'tester_notes':it.get('t',[])}
# shops and tuners who do the work (revalves, ECU flashes): the Garage "who did it?" list. Fitment is the makes the service
# names; an empty list means the service is offered without a bike list.
providers=[]
for f in sorted(glob.glob(os.path.join(root,'docs','research','aftermarket','specialty','*.json'))):
    for p in json.load(open(f)).get('products',[]):
        if not p.get('is_service'): continue
        sub=str(p.get('subcategory') or '').lower()
        work='ecu' if re.search(r'ecu|flash|map',sub) else 'suspension' if re.search(r'revalve|suspension|valv',sub) else None
        if not work: continue
        makes=sorted({m.strip() for x in p.get('fits') or [] for m in re.split(r'[/,&]| and ',str(x.get('make',''))) if m.strip()})
        models=sorted({m.strip()+'|'+str(x.get('model','')).strip() for x in p.get('fits') or [] for m in re.split(r'[/,&]| and ',str(x.get('make',''))) if m.strip() and x.get('model')})
        b=brand_name(p.get('brand'))
        providers.append({'id':p['id'],'brand':b,'models':models,'name':short(re.sub(r'^'+re.escape(b)+r'\s+','',str(p.get('product') or '')),90),'work':work,'makes':makes,'conf':p.get('confidence')})
        research.setdefault(p['id'],{'brand':b,'product':short(p.get('product'),90),'system':'tuning' if work=='ecu' else 'suspension','part_numbers':' '.join(p.get('part_numbers') or [])[:48],
            'confidence':p.get('confidence'),'what_it_changes':short(p.get('what_it_changes'),220),
            'caveats':short(' '.join(str(x) for x in (p.get('supporting_parts'),p.get('caveats')) if x),220),
            'tester_notes':[short(x,160) for x in (p.get('rider_feedback') or []) if isinstance(x,str) and x.strip()][:2]})
open(os.path.join(root,'shared','work-providers.ts'),'w').write('// GENERATED by scripts/aftermarket/build_app_data.py. Do not edit by hand.\n'
    '// Shops and tuners that do suspension revalves and ECU flashes, for the Garage "who did the work?" list. makes empty = no bike list published.\n'
    'export type WorkProvider={id:string;brand:string;name:string;work:\'ecu\'|\'suspension\';models:string[];makes:string[];conf:string|null};\n'
    'export const workProviders:WorkProvider[]='+json.dumps(providers,separators=(',',':'),ensure_ascii=False)+';\n')
print(len(providers),'work providers')
dst=os.path.join(root,'shared','aftermarket-research.ts')
open(dst,'w').write('// GENERATED by scripts/aftermarket/build_app_data.py. Do not edit by hand.\n'
    '// Researched aftermarket parts (research-grade, attributed; not verified evidence), keyed by the id a Garage pick stores.\n'
    'export type ResearchedPart={brand:string;product:string;system:string;part_numbers:string;confidence:string|null;what_it_changes:string;caveats:string;tester_notes:string[]};\n'
    'export const researchedParts:Record<string,ResearchedPart>='+json.dumps(research,separators=(',',':'),ensure_ascii=False)+';\n')
print(len(research),'researched parts ->',os.path.getsize(dst)//1024,'KB')
