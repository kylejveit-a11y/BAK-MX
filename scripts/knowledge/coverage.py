#!/usr/bin/env python3
"""Deep-knowledge coverage scorecard (docs/research/BIKE_KNOWLEDGE_STANDARD.md, "How coverage is scored").

Input: a JSON export of approved bike_knowledge counts, one object per bike-year-domain:
  {"manufacturer","model","model_year","domain","n","strong"}   (strong = rows at OEM or MEASURED tier)
produced by:
  select manufacturer,model,model_year,domain,count(*) n,
         count(*) filter (where tier in ('OEM','MEASURED')) strong
  from bike_knowledge where status='APPROVED' group by 1,2,3,4;

Every roster bike-year (shared/garage-models.ts) is scored per domain:
  100 = at least 3 rows and at least one OEM/MEASURED row (DERIVED counts as strong for drivetrain)
   60 = at least one OEM/MEASURED row, or 3+ rows at any tier
   30 = one or two rows at TUNER/DERIVED/COMMUNITY tier only
    0 = nothing
The bike-year score is the mean over the 11 domains. Output: docs/research/knowledge/COVERAGE.md
Usage: python3 scripts/knowledge/coverage.py <export.json> [out.md]
"""
import json, re, sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOMAINS = ['identity', 'engine_architecture', 'power_feel', 'ecu_electronics', 'engine_mods', 'chassis',
           'suspension', 'drivetrain', 'maintenance', 'known_issues', 'setups']
SHORT = {'identity': 'ID', 'engine_architecture': 'Eng', 'power_feel': 'Pwr', 'ecu_electronics': 'ECU',
         'engine_mods': 'Mods', 'chassis': 'Chs', 'suspension': 'Susp', 'drivetrain': 'Drv',
         'maintenance': 'Mnt', 'known_issues': 'Iss', 'setups': 'Set'}


def roster():
    src = (ROOT / 'shared/garage-models.ts').read_text()
    def obj(name):
        m = re.search(r'const ' + name + r'[^=]*=(\{.*?\});\n', src)
        return json.loads(m.group(1))
    years, info = obj('confirmedYears'), obj('garageModelInfo')
    return [(k.split('|')[0], k.split('|')[1], y, info.get(k, {}).get('discipline', '')) for k, ys in years.items() for y in ys]


def load(path):
    text = Path(path).read_text()
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        data = text
    if isinstance(data, dict):  # the SQL tool wraps the rows in {"result": "...text... [rows] ..."}
        data = data.get('result', '')
    if isinstance(data, str):
        data = json.loads(re.search(r'\[\s*\{.*\}\s*\]', data, re.S).group(0))
    return data


def score(n, strong, domain):
    if n == 0:
        return 0
    if strong and n >= 3:
        return 100
    if strong or n >= 3:
        return 60
    return 30


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / 'docs/research/knowledge/COVERAGE.md'
    cells = defaultdict(lambda: (0, 0))
    for r in load(sys.argv[1]):
        n, strong = int(r['n']), int(r['strong'])
        if r['domain'] == 'drivetrain':
            strong = max(strong, 1 if n else 0)  # derived gearing works from manufacturer ratios
        cells[(r['manufacturer'], r['model'], int(r['model_year']), r['domain'])] = (n, strong)

    bikes = sorted(roster())
    rows, by_model = [], defaultdict(list)
    for make, model, year, disc in bikes:
        s = {d: score(*cells[(make, model, year, d)], d) for d in DOMAINS}
        total = round(sum(s.values()) / len(DOMAINS))
        n = sum(cells[(make, model, year, d)][0] for d in DOMAINS)
        rows.append((make, model, year, disc, s, total, n))
        by_model[(make, model, disc)].append((year, total, n))

    all_scores = [r[5] for r in rows]
    full = sum(1 for r in rows if r[5] >= 80)
    empty = sum(1 for r in rows if r[6] == 0)
    dom_avg = {d: round(sum(r[4][d] for r in rows) / len(rows)) for d in DOMAINS}

    L = ['# Deep-knowledge coverage scorecard', '',
         'Generated by `scripts/knowledge/coverage.py` from approved `bike_knowledge` rows. Scoring per domain: 100 = 3+ rows',
         'with at least one manufacturer or independently measured source; 60 = one strong source or 3+ rows; 30 = one or two',
         'weaker-tier rows; 0 = nothing. A bike-year is the mean of the 11 domains. This covers deep knowledge only; published',
         'specs, manual settings and the parts catalog are tracked separately in `docs/research/COVERAGE.md`.', '',
         f'- Roster bike-years: **{len(rows)}**',
         f'- Mean score: **{round(sum(all_scores) / len(all_scores))}**',
         f'- Bike-years at 80+: **{full}**',
         f'- Bike-years with no deep knowledge yet: **{empty}**', '',
         '## Average by domain', '', '| ' + ' | '.join(SHORT[d] for d in DOMAINS) + ' |',
         '|' + '---|' * len(DOMAINS), '| ' + ' | '.join(str(dom_avg[d]) for d in DOMAINS) + ' |', '',
         '## By model', '', '| Make | Model | Type | Years | Mean | Lowest year | Rows |', '|---|---|---|---|---|---|---|']
    for (make, model, disc), ys in sorted(by_model.items(), key=lambda kv: (sum(t for _, t, _ in kv[1]) / len(kv[1]))):
        lo = min(ys, key=lambda x: x[1])
        L.append(f'| {make} | {model} | {disc} | {min(y for y, _, _ in ys)}-{max(y for y, _, _ in ys)} | '
                 f'{round(sum(t for _, t, _ in ys) / len(ys))} | {lo[0]} ({lo[1]}) | {sum(n for _, _, n in ys)} |')
    L += ['', '## Every bike-year', '', '| Bike | ' + ' | '.join(SHORT[d] for d in DOMAINS) + ' | Score |',
          '|---|' + '---|' * (len(DOMAINS) + 1)]
    for make, model, year, disc, s, total, n in rows:
        L.append(f'| {year} {make} {model} | ' + ' | '.join(str(s[d]) for d in DOMAINS) + f' | **{total}** |')
    out.write_text('\n'.join(L) + '\n')
    print(f'{len(rows)} bike-years, mean {round(sum(all_scores) / len(all_scores))}, 80+: {full}, empty: {empty} -> {out}')
    print('domain averages:', dom_avg)


if __name__ == '__main__':
    main()
