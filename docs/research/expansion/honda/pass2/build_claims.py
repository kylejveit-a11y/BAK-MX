"""Honda pass 2 facts -> SQL inserts for public.claims, same column set and evidence_record shape as the existing Honda rows.

usage: python3 build_claims.py            (writes claims.sql and claims_2027.sql beside this file; prints row counts)
Reads every <year>-<model>-facts.json beside this file (values reviewed in REVIEW.md). 2027 rows go to claims_2027.sql only,
because whether 2027 Honda enters the app's bike list is decided separately. Ids are stable (uuid5 of model|year|joint), so
re-running produces the same rows; inserts use ON CONFLICT (id) DO NOTHING. Nothing here touches a database."""
import glob, json, os, uuid
from collections import Counter
HERE = os.path.dirname(os.path.abspath(__file__))
NS = uuid.UUID('6c1e2f0a-5d3b-4f7e-9a21-0bda2a55c0de')
REVIEWED_AT = '2026-10-25T00:00:00Z'
REVIEWER = 'BAK MX manufacturer source review (pass 2: document text layer plus rendered page-image check)'
REF = 'docs/research/expansion/honda/pass2/REVIEW.md'

def q(s):
    return "'" + str(s).replace("'", "''") + "'"

def rows_for(path):
    d = json.load(open(path))
    t, src = d['target'], d['source_document']
    model, year = t['model'], t['model_year']
    app = {'model': model, 'region': 'US', 'variant': 'standard', 'model_year': year, 'manufacturer': 'Honda'}
    out = []
    for v in d['values']:
        joint, value, unit, conds = v['joint'], v['value'], v.get('unit'), v['conditions']
        vsrc = v.get('source', src)   # owner's-manual values carried in a handbook year cite their own document
        statement = f"{joint}: {value}{(' ' + unit) if unit else ''}. {' '.join(conds)}".strip()
        locator = f"PDF page {v['pdf_page']}; printed {v['printed_page']}; {joint}"
        rid = str(uuid.uuid5(NS, f"Honda|{model}|{year}|{joint}"))
        reviewed = {'unit': unit, 'joint': joint, 'value': value, 'property': v['property'], 'conditions': conds}
        ev = {'id': rid, 'domain': 'service',
              'review': {'decision': 'approved', 'reviewed_at': REVIEWED_AT, 'reviewer_id': REVIEWER,
                         'scope_checked': True, 'content_checked': True, 'conflicts_checked': True,
                         'approval_reference': f"{REF}; OEM document from Honda's CDN, hashed; value matched to the text layer of the cited page by extract_pass2.py and the page image checked; model assignment as recorded in the review; no same-scope row on file.",
                         'approved_applicability': app, 'approved_document_sha256': vsrc['document_sha256']},
              'rights': {'basis': 'factual_extraction', 'reference': f'Existing BAK MX US factual-extraction policy; {REF}',
                         'usage_scope': 'facts_only_no_source_distribution', 'commercial_use_approved': True},
              'source': {'url': vsrc['source_url'], 'kind': 'document', 'locator': locator, 'retrieved_at': REVIEWED_AT,
                         'document_sha256': vsrc['document_sha256'], 'reviewed_content': json.dumps(reviewed, ensure_ascii=False),
                         'document_revision': vsrc['document_revision']},
              'status': 'STAGED', 'statement': statement, 'has_conflict': False, 'applicability': app, 'conflict_references': []}
        out.append((rid, model, year, statement, vsrc['source_url'], locator, ev, v['property']))
    return out

def write(rows, fn):
    with open(os.path.join(HERE, fn), 'w') as f:
        f.write('-- generated by build_claims.py; Honda pass 2 (see REVIEW.md)\n')
        f.write('insert into public.claims (id,manufacturer,model,model_year,variant,region,domain,statement,source_url,source_locator,status,has_conflict,evidence_record) values\n')
        f.write(',\n'.join(f"({q(r[0])},'Honda',{q(r[1])},{r[2]},'standard','US','service',{q(r[3])},{q(r[4])},{q(r[5])},'VERIFIED',false,{q(json.dumps(r[6], ensure_ascii=False))}::jsonb)" for r in rows))
        f.write('\non conflict (id) do nothing;\n')

main, y27 = [], []
for p in sorted(glob.glob(os.path.join(HERE, '20*-facts.json'))):
    rs = rows_for(p)
    (y27 if '/2027-' in p else main).extend(rs)
ids = [r[0] for r in main + y27]
assert len(ids) == len(set(ids)), 'duplicate ids'
write(main, 'claims.sql'); write(y27, 'claims_2027.sql')
for name, rs in (('claims.sql', main), ('claims_2027.sql', y27)):
    print(name, len(rs), dict(sorted(Counter(f'{r[2]} {r[1]}' for r in rs).items())))
